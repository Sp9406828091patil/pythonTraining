# python logical operators

# 'and' operator
x = 6
print(x > 5 and x < 10)

# 'or' operator
x = 6
print(x > 5 or x > 10)

# 'not' operator
x = 6
print(not(x > 5 and x < 10))
newString = "Aboli"
print(newString != "Abolia")

# python identity operator
print(type(newString))
print(newString is 'str')
print(not(isinstance(newString, str)))
